-- Building task assignments (generated per day)
CREATE TABLE IF NOT EXISTS building_tasks (
    id                  INTEGER PRIMARY KEY,
    building_id         INTEGER NOT NULL REFERENCES buildings(id),
    task_type_id        INTEGER NOT NULL REFERENCES task_types(id),
    estimated_hours     REAL NOT NULL,
    assigned_to         INTEGER REFERENCES custodians(id),
    scheduled_start     TEXT,
    scheduled_end       TEXT,
    status              TEXT DEFAULT 'unassigned',
    schedule_date       TEXT,
    notes               TEXT
);

-- Disruptions (callouts, events, special projects)
CREATE TABLE IF NOT EXISTS disruptions (
    id                  INTEGER PRIMARY KEY,
    disruption_date     TEXT NOT NULL,
    type                TEXT NOT NULL,  -- 'callout', 'event', 'special_project', 'vacation'
    custodian_id        INTEGER REFERENCES custodians(id),
    building_id         INTEGER REFERENCES buildings(id),
    description         TEXT,
    extra_hours         REAL DEFAULT 0,
    resolved            BOOLEAN DEFAULT FALSE,
    created_at          TEXT DEFAULT (datetime('now'))
);
